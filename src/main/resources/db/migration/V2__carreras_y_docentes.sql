-- Carreras como tabla propia, perfil de docentes y asignación de docente/carrera a cada materia.
-- Convierte los datos existentes: cada texto distinto de estudiantes.carrera pasa a ser una carrera.

CREATE TABLE carreras (
    id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(20)  NOT NULL UNIQUE,
    nombre VARCHAR(120) NOT NULL UNIQUE
);

INSERT INTO carreras (codigo, nombre)
SELECT CASE WHEN carrera = 'Ingeniería en Informática' THEN 'INF'
            ELSE 'CAR-' || ROW_NUMBER() OVER (ORDER BY carrera) END,
       carrera
FROM (SELECT DISTINCT carrera FROM estudiantes) AS existentes;

-- Estudiantes: texto libre -> referencia a carreras
ALTER TABLE estudiantes ADD COLUMN carrera_id BIGINT REFERENCES carreras (id);
UPDATE estudiantes e SET carrera_id = c.id FROM carreras c WHERE c.nombre = e.carrera;
ALTER TABLE estudiantes ALTER COLUMN carrera_id SET NOT NULL;
ALTER TABLE estudiantes DROP COLUMN carrera;

-- Materias: toda materia pertenece a una carrera. Las existentes van a la primera carrera
-- (o a una genérica si no había estudiantes); el administrador puede cambiarlas después.
INSERT INTO carreras (codigo, nombre)
SELECT 'GEN', 'Sin carrera asignada'
WHERE EXISTS (SELECT 1 FROM materias) AND NOT EXISTS (SELECT 1 FROM carreras);

ALTER TABLE materias ADD COLUMN carrera_id BIGINT REFERENCES carreras (id);
UPDATE materias SET carrera_id = (SELECT MIN(id) FROM carreras);
ALTER TABLE materias ALTER COLUMN carrera_id SET NOT NULL;

-- Perfil de cada docente (nombre completo); los usuarios DOCENTE existentes usan su usuario como nombre
CREATE TABLE docentes (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id      BIGINT       NOT NULL UNIQUE REFERENCES usuarios (id),
    nombre_completo VARCHAR(150) NOT NULL
);

INSERT INTO docentes (usuario_id, nombre_completo)
SELECT id, username FROM usuarios WHERE rol = 'DOCENTE';

-- Docente a cargo de cada materia (opcional). Si había un único docente, queda a cargo de todas.
ALTER TABLE materias ADD COLUMN docente_id BIGINT REFERENCES docentes (id);
UPDATE materias SET docente_id = (SELECT MIN(id) FROM docentes)
WHERE (SELECT COUNT(*) FROM docentes) = 1;
