-- Asistencia, inscripción por materia, exoneraciones y notas desglosadas (reglamento UPE).

-- Porcentaje mínimo de asistencia para tener derecho al examen final.
-- La carrera define el valor por defecto (70 %); cada materia puede tener el suyo (NULL = el de la carrera).
ALTER TABLE carreras ADD COLUMN asistencia_minima INTEGER NOT NULL DEFAULT 70
    CHECK (asistencia_minima BETWEEN 0 AND 100);
ALTER TABLE materias ADD COLUMN asistencia_minima INTEGER CHECK (asistencia_minima BETWEEN 0 AND 100);
-- Clases previstas en el semestre (opcional): permite calcular cuántas faltas le quedan a cada alumno
ALTER TABLE materias ADD COLUMN clases_previstas INTEGER CHECK (clases_previstas BETWEEN 1 AND 300);

-- Estudiantes que cursan cada materia
CREATE TABLE inscripciones (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estudiante_id  BIGINT NOT NULL REFERENCES estudiantes (id),
    materia_id     BIGINT NOT NULL REFERENCES materias (id),
    fecha_registro TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_inscripcion_estudiante_materia UNIQUE (estudiante_id, materia_id)
);
CREATE INDEX ix_inscripciones_materia ON inscripciones (materia_id);

-- Quien ya tiene nota en una materia la está cursando: se lo inscribe para no perder nada
INSERT INTO inscripciones (estudiante_id, materia_id, fecha_registro)
SELECT estudiante_id, materia_id, CURRENT_TIMESTAMP FROM calificaciones;

-- Cada clase dictada (una por día y materia) y la asistencia de cada inscripto
CREATE TABLE clases (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    materia_id     BIGINT NOT NULL REFERENCES materias (id),
    fecha          DATE   NOT NULL,
    tema           VARCHAR(200),
    fecha_registro TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_clase_materia_fecha UNIQUE (materia_id, fecha)
);

CREATE TABLE asistencias (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    clase_id      BIGINT      NOT NULL REFERENCES clases (id),
    estudiante_id BIGINT      NOT NULL REFERENCES estudiantes (id),
    estado        VARCHAR(12) NOT NULL CHECK (estado IN ('PRESENTE', 'TARDE', 'AUSENTE', 'JUSTIFICADO')),
    observacion   VARCHAR(200),
    CONSTRAINT uk_asistencia_clase_estudiante UNIQUE (clase_id, estudiante_id)
);
CREATE INDEX ix_asistencias_estudiante ON asistencias (estudiante_id);

-- Exoneración de asistencia por causa justificada (hasta 2 materias por semestre)
CREATE TABLE exoneraciones (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estudiante_id  BIGINT       NOT NULL REFERENCES estudiantes (id),
    materia_id     BIGINT       NOT NULL REFERENCES materias (id),
    motivo         VARCHAR(300) NOT NULL,
    otorgada_por   VARCHAR(50)  NOT NULL,
    fecha_registro TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_exoneracion_estudiante_materia UNIQUE (estudiante_id, materia_id)
);

-- Notas desglosadas: 2 parciales de 15, trabajo práctico de 20 y examen final de 50 (total 100).
-- Las notas existentes quedan como "nota única" (componentes en NULL).
ALTER TABLE calificaciones ADD COLUMN primer_parcial   INTEGER CHECK (primer_parcial BETWEEN 0 AND 15);
ALTER TABLE calificaciones ADD COLUMN segundo_parcial  INTEGER CHECK (segundo_parcial BETWEEN 0 AND 15);
ALTER TABLE calificaciones ADD COLUMN trabajo_practico INTEGER CHECK (trabajo_practico BETWEEN 0 AND 20);
ALTER TABLE calificaciones ADD COLUMN examen_final     INTEGER CHECK (examen_final BETWEEN 0 AND 50);
