-- Super administrador y buzón de solicitudes (olvidé mi contraseña / pedido de acceso).

-- Un único super administrador: el único que puede eliminar, desactivar o cambiar la contraseña
-- de otros administradores. En las bases existentes lo es el primer administrador creado.
ALTER TABLE usuarios ADD COLUMN super_admin BOOLEAN NOT NULL DEFAULT FALSE;
UPDATE usuarios SET super_admin = TRUE
WHERE id = (SELECT MIN(id) FROM usuarios WHERE rol = 'ADMIN');
CREATE UNIQUE INDEX ux_usuarios_un_super_admin ON usuarios (super_admin) WHERE super_admin;

-- Pedidos que se envían desde la pantalla de inicio de sesión sin estar logueado.
-- Se guarda el usuario como texto (puede no existir) para que borrar un usuario no borre su historial.
CREATE TABLE solicitudes (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo            VARCHAR(20)  NOT NULL CHECK (tipo IN ('CONTRASENA', 'ACCESO')),
    username        VARCHAR(50),
    nombre          VARCHAR(150),
    contacto        VARCHAR(150),
    mensaje         VARCHAR(500),
    estado          VARCHAR(12)  NOT NULL CHECK (estado IN ('PENDIENTE', 'RESUELTA', 'DESCARTADA')),
    fecha_registro  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    atendida_por    VARCHAR(50),
    fecha_atencion  TIMESTAMP(6) WITH TIME ZONE
);
CREATE INDEX ix_solicitudes_estado ON solicitudes (estado, fecha_registro);
