-- Esquema inicial: el mismo que generaba Hibernate antes de usar migraciones.
-- Las bases creadas antes de Flyway se marcan como "ya en V1" (baseline) y no ejecutan este archivo.

CREATE TABLE usuarios (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    activo        BOOLEAN     NOT NULL,
    password_hash VARCHAR(60) NOT NULL,
    rol           VARCHAR(20) NOT NULL CHECK (rol IN ('ADMIN', 'DOCENTE', 'ESTUDIANTE')),
    username      VARCHAR(50) NOT NULL UNIQUE
);

CREATE TABLE estudiantes (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    carrera         VARCHAR(100) NOT NULL,
    matricula       VARCHAR(20)  NOT NULL UNIQUE,
    nombre_completo VARCHAR(150) NOT NULL,
    usuario_id      BIGINT       NOT NULL UNIQUE REFERENCES usuarios (id)
);

CREATE TABLE materias (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo   VARCHAR(20)  NOT NULL UNIQUE,
    creditos INTEGER      NOT NULL,
    nombre   VARCHAR(120) NOT NULL,
    semestre INTEGER      NOT NULL CHECK (semestre BETWEEN 1 AND 12)
);

CREATE TABLE calificaciones (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_actualizacion TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    fecha_registro      TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    nota                INTEGER NOT NULL,
    estudiante_id       BIGINT  NOT NULL REFERENCES estudiantes (id),
    materia_id          BIGINT  NOT NULL REFERENCES materias (id),
    CONSTRAINT uk_calificacion_estudiante_materia UNIQUE (estudiante_id, materia_id),
    CONSTRAINT ck_calificacion_nota_rango CHECK (nota BETWEEN 0 AND 100)
);
